-- Esquema de reservas-soa en PostgreSQL (Supabase).
-- Un esquema por contexto acotado, igual que las bases SQLite: identidad (S1, S2),
-- vuelos (S3) y reservas (S4, S5). Ejecutar una vez antes de iniciar los servicios.
-- Las tablas reflejan shared/models.py. Los servicios no crean esquemas.

CREATE SCHEMA IF NOT EXISTS identidad;
CREATE SCHEMA IF NOT EXISTS vuelos;
CREATE SCHEMA IF NOT EXISTS reservas;

CREATE TABLE IF NOT EXISTS identidad.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    rol varchar(20) NOT NULL DEFAULT 'cliente',
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('cliente', 'administrador'))
);

CREATE TABLE IF NOT EXISTS vuelos.vuelos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen varchar(100) NOT NULL,
    destino varchar(100) NOT NULL,
    fecha date NOT NULL,
    hora varchar(5) NOT NULL DEFAULT '08:00',
    precio double precision NOT NULL,
    asientos_disponibles integer NOT NULL,
    activo boolean NOT NULL DEFAULT false,
    CONSTRAINT ck_vuelos_disponibles_no_negativos CHECK (asientos_disponibles >= 0),
    CONSTRAINT ck_vuelos_disponibles_maximo CHECK (asientos_disponibles <= 180)
);

CREATE TABLE IF NOT EXISTS vuelos.asientos_vuelo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vuelo_id integer NOT NULL,
    codigo varchar(10) NOT NULL,
    fila integer NOT NULL,
    columna varchar(1) NOT NULL,
    reserva_id integer NULL,
    CONSTRAINT uq_asiento_vuelo_codigo UNIQUE (vuelo_id, codigo),
    CONSTRAINT ck_asiento_columna CHECK (columna IN ('A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'))
);
CREATE INDEX IF NOT EXISTS ix_asientos_vuelo_vuelo_id ON vuelos.asientos_vuelo (vuelo_id);
CREATE INDEX IF NOT EXISTS ix_asientos_vuelo_reserva_id ON vuelos.asientos_vuelo (reserva_id);

CREATE TABLE IF NOT EXISTS reservas.reservas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_email varchar(255) NOT NULL,
    vuelo_id integer NOT NULL,
    pasajero varchar(100) NOT NULL,
    estado varchar(20) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_reservas_usuario_email ON reservas.reservas (usuario_email);

CREATE TABLE IF NOT EXISTS reservas.reserva_asientos (
    reserva_id integer PRIMARY KEY,
    vuelo_id integer NOT NULL,
    asiento varchar(10) NOT NULL
);

-- Las tablas no se exponen por la API REST de Supabase (solo el esquema public).
-- RLS queda activo sin politicas: el rol postgres (que usan los servicios) lo omite;
-- anon y authenticated no pueden leer ni escribir.
ALTER TABLE identidad.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE vuelos.vuelos ENABLE ROW LEVEL SECURITY;
ALTER TABLE vuelos.asientos_vuelo ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservas.reservas ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservas.reserva_asientos ENABLE ROW LEVEL SECURITY;
