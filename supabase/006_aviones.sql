-- Registro de aviones (S6) y avión asignado a cada vuelo.
-- Idempotente: se puede ejecutar más de una vez. Ejecutar después de 005.
-- Las tablas reflejan shared/models.py (Avion, Vuelo.avion_id). Los servicios no crean esquemas.

CREATE SCHEMA IF NOT EXISTS aviones;

-- Avión: nombre único y capacidad = número de asientos (18 a 180, múltiplo de 6, filas de 3 + 3).
CREATE TABLE IF NOT EXISTS aviones.aviones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(60) NOT NULL UNIQUE,
    capacidad integer NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_aviones_capacidad CHECK (capacidad >= 18 AND capacidad <= 180 AND capacidad % 6 = 0)
);

-- Igual que el resto de tablas: sin políticas, solo el rol de los servicios accede.
ALTER TABLE aviones.aviones ENABLE ROW LEVEL SECURITY;

-- Vuelo: avión asignado. NULL = vuelo anterior al registro de aviones (conserva su mapa de asientos).
ALTER TABLE vuelos.vuelos ADD COLUMN IF NOT EXISTS avion_id integer NULL;
CREATE INDEX IF NOT EXISTS ix_vuelos_avion_id ON vuelos.vuelos (avion_id);
