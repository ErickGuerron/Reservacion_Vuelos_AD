-- Cambios sobre 001_esquema.sql: lote de reservas (factura), precio por asiento y tokens emitidos.
-- Idempotente: se puede ejecutar mas de una vez. Ejecutar despues de 001.

-- Lote: reservas de una misma compra comparten lote_id (NULL = reserva anterior al lote).
ALTER TABLE reservas.reservas ADD COLUMN IF NOT EXISTS lote_id integer NULL;
ALTER TABLE reservas.reservas ADD COLUMN IF NOT EXISTS precio double precision NULL;
CREATE INDEX IF NOT EXISTS ix_reservas_lote_id ON reservas.reservas (lote_id);

-- Tokens emitidos en cada login (S2). Se guarda el SHA-256 del JWT, nunca el JWT.
CREATE TABLE IF NOT EXISTS identidad.tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer NOT NULL REFERENCES identidad.usuarios (id),
    token varchar(64) NOT NULL UNIQUE,
    expiracion timestamptz NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'activo'
);
CREATE INDEX IF NOT EXISTS ix_tokens_usuario_id ON identidad.tokens (usuario_id);

ALTER TABLE identidad.tokens ENABLE ROW LEVEL SECURITY;
